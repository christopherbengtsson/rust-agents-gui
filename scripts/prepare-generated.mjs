// Sole owner of managed generated assets. Check mode never repairs source files.
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { cargoMetadata, claimTarget, root, runCommand } from "./cargo.mjs";

const directory = path.join(root, "src/generated/contracts");
export function reconcileArtifacts(
  expected,
  mode,
  {
    list = () => {
      try {
        return readdirSync(directory).sort();
      } catch (error) {
        if (error.code === "ENOENT") return [];
        throw error;
      }
    },
    read = (name) => readFileSync(path.join(directory, name), "utf8"),
    write = (name, content) => {
      mkdirSync(directory, { recursive: true });
      writeFileSync(path.join(directory, name), content);
    },
    remove = (name) => rmSync(path.join(directory, name)),
  } = {},
) {
  if (!["--check", "--write"].includes(mode))
    throw new Error("Expected --write or --check");
  const present = new Set(list());
  const differences = [];
  for (const [name, content] of Object.entries(expected)) {
    if (!present.has(name)) differences.push(`missing: ${name}`);
    else if (read(name) !== content) differences.push(`stale: ${name}`);
  }
  const obsolete = [...present].filter((name) => !(name in expected)).sort();
  differences.push(...obsolete.map((name) => `unexpected: ${name}`));
  if (mode === "--check" && differences.length)
    throw new Error(
      `Generated contract drift; run corepack pnpm generated:write:\n${differences.join("\n")}`,
    );
  if (mode === "--write") {
    for (const [name, content] of Object.entries(expected))
      write(name, content);
    for (const name of obsolete) remove(name);
  }
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
export function renderArtifacts(exported) {
  const ajv = new Ajv2020({ code: { source: true, esm: true }, strict: true });
  addFormats(ajv, ["uuid"]);
  // Schemars numeric formats accompany integer/minimum keywords, but not always a maximum.
  // Contextual assertions retain JS-safe counters and the PID upper bound.
  for (const format of ["uint32", "uint64", "uint", "int32", "int64", "int"])
    ajv.addFormat(format, true);
  const validators = {};
  for (const [name, schema] of Object.entries(exported.schemas)) {
    const id = `urn:agent-workspace:contracts:${name}`;
    ajv.addSchema(schema, id);
    validators[`validate${name}`] = id;
  }
  const code = standaloneCode(ajv, validators);
  // New schema features requiring helpers must acquire explicit static ESM imports.
  if (/\brequire\s*\(|\beval\s*\(|new Function\b/.test(code))
    throw new Error(
      "Standalone validators require an explicit ESM runtime helper; refusing unsafe output",
    );
  const names = Object.keys(exported.schemas);
  const expected = {
    // ts-rs may leave spaces before a newline when a field has documentation.
    "types.ts": exported.declarations.replace(/[ \t]+$/gm, ""),
    "schemas.json": json(exported.schemas),
    "validators.js": `// Generated by Ajv standalone. Do not edit.\n${code}\n`,
    "validators.d.ts": `// Generated. Do not edit.\nimport type { ${names.join(", ")} } from "./types";\n${names.map((name) => `export declare function validate${name}(value: unknown): value is ${name};`).join("\n")}\n`,
  };
  const sources = [
    "Cargo.toml",
    "Cargo.lock",
    "crates/core/Cargo.toml",
    "crates/core/src/lib.rs",
    "crates/core/src/codegen.rs",
    "crates/core/src/bin/export-contracts.rs",
    "crates/core/src/connection.rs",
    "crates/core/src/connection/subscription.rs",
    "crates/core/src/observations.rs",
    "crates/core/src/workspaces.rs",
    "crates/core/src/workspaces/creation.rs",
    "crates/core/src/workspaces/inspection.rs",
    "package.json",
    "pnpm-lock.yaml",
    "scripts/prepare-generated.mjs",
  ];
  expected["manifest.json"] = json({
    format: 1,
    generators: {
      "ts-rs": "12.0.1",
      schemars: "1.2.3",
      ajv: "8.20.0",
      "ajv-formats": "3.0.1",
    },
    contract: "draft2020-12 serialization; JSON numbers; UUID formats",
    sources: Object.fromEntries(
      sources.map((name) => [
        name,
        sha256(readFileSync(path.join(root, name))),
      ]),
    ),
    artifacts: Object.fromEntries(
      Object.entries(expected).map(([name, content]) => [
        name,
        sha256(content),
      ]),
    ),
  });
  return expected;
}

export function prepareGenerated(
  mode,
  {
    run = runCommand,
    claim = claimTarget,
    render = renderArtifacts,
    reconcile = reconcileArtifacts,
  } = {},
) {
  if (!["--write", "--check"].includes(mode))
    throw new Error("Expected --write or --check");
  const metadata = cargoMetadata(run);
  const core = metadata.packages.find((pkg) => pkg.name === "workspace-core");
  if (!core) throw new Error("workspace-core missing from Cargo metadata");
  claim(metadata.target_directory);
  const output = run("cargo", [
    "build",
    "--locked",
    "-p",
    "workspace-core",
    "--bin",
    "export-contracts",
    "--features",
    "codegen",
    "--message-format=json-render-diagnostics",
  ]);
  const artifacts = output
    .split("\n")
    .filter((line) => line.startsWith("{"))
    .map((line) => JSON.parse(line))
    .filter(
      (message) =>
        message.reason === "compiler-artifact" &&
        message.package_id === core.id &&
        message.target?.name === "export-contracts" &&
        message.target.kind.includes("bin") &&
        !message.profile.test &&
        message.executable,
    );
  if (artifacts.length !== 1)
    throw new Error(
      "Cargo must report exactly one contract exporter; nothing written",
    );
  const exported = JSON.parse(run(artifacts[0].executable, []));
  reconcile(render(exported), mode);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  prepareGenerated(process.argv[2]);
  console.log(
    process.argv[2] === "--check"
      ? "Generated contracts match source"
      : "Generated contracts written",
  );
}
