//! Pure export of frontend wire contracts. No filesystem or application effects.
use schemars::{JsonSchema, generate::SchemaSettings};
use serde::Serialize;
use serde_json::Value;
use std::collections::BTreeMap;
use ts_rs::{Config, TS};

#[derive(Serialize)]
pub struct ContractExport {
    pub declarations: String,
    pub schemas: BTreeMap<String, Value>,
}

pub(crate) struct Exports {
    config: Config,
    declarations: BTreeMap<String, String>,
    schemas: BTreeMap<String, Value>,
}
impl Exports {
    pub(crate) fn add<T: TS + JsonSchema>(&mut self) {
        let name = T::ident(&self.config);
        self.declarations
            .insert(name.clone(), format!("export {}", T::decl(&self.config)));
        self.schema::<T>(&name);
    }
    pub(crate) fn schema<T: JsonSchema>(&mut self, name: &str) {
        let schema = SchemaSettings::draft2020_12()
            .for_serialize()
            .into_generator()
            .into_root_schema_for::<T>();
        assert!(
            self.schemas
                .insert(
                    name.into(),
                    serde_json::to_value(schema).expect("schema serialization is infallible")
                )
                .is_none(),
            "duplicate schema {name}"
        );
    }
    pub(crate) fn owned_replies(&mut self) {
        use crate::{
            connection::OwnedReply,
            workspaces::{RepositoryReply, WorkspaceReply},
        };
        self.declarations.insert(
            "OwnedReply".into(),
            format!(
                "export {}",
                OwnedReply::<RepositoryReply>::decl(&self.config)
            ),
        );
        self.alias("OwnedObservation", "OwnedReply<unknown>");
        self.schema::<OwnedReply<Value>>("OwnedObservation");
        self.alias(
            "OwnedRepositoryReply",
            &OwnedReply::<RepositoryReply>::name(&self.config),
        );
        self.schema::<OwnedReply<RepositoryReply>>("OwnedRepositoryReply");
        self.alias(
            "OwnedWorkspaceReply",
            &OwnedReply::<WorkspaceReply>::name(&self.config),
        );
        self.schema::<OwnedReply<WorkspaceReply>>("OwnedWorkspaceReply");
        self.alias(
            "OwnedProviderReply",
            &OwnedReply::<crate::runtimes::ProviderReply>::name(&self.config),
        );
        self.schema::<OwnedReply<crate::runtimes::ProviderReply>>("OwnedProviderReply");
    }
    pub(crate) fn alias(&mut self, name: &str, ty: &str) {
        assert!(
            self.declarations
                .insert(name.into(), format!("export type {name} = {ty};"))
                .is_none(),
            "duplicate declaration {name}"
        );
    }
}

pub fn render() -> ContractExport {
    let mut exports = Exports {
        // Never consult ambient TS_RS_* environment variables.
        config: Config::new()
            .with_large_int("number")
            .with_import_extension(Some(".js")),
        declarations: BTreeMap::new(),
        schemas: BTreeMap::new(),
    };
    crate::runtimes::export_contracts(&mut exports);
    exports.add::<crate::CoreState>();
    exports.add::<crate::CoreStatus>();
    exports.add::<crate::SnapshotCursor>();
    exports.add::<crate::CoreSnapshot>();
    exports.alias("DesktopPid", &crate::DesktopPid::inline(&exports.config));
    exports.schema::<crate::DesktopPid>("DesktopPid");
    crate::connection::export_contracts(&mut exports);
    crate::workspaces::export_contracts(&mut exports);
    crate::observations::export_contracts(&mut exports);
    ContractExport {
        declarations: format!(
            "// Generated by workspace-core codegen. Do not edit.\n{}\n",
            exports
                .declarations
                .into_values()
                .collect::<Vec<_>>()
                .join("\n")
        ),
        schemas: exports.schemas,
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn serialized_registration_defaults_are_required_and_flattened() {
        let exported = super::render();
        let schema = &exported.schemas["Registration"];
        let required = schema["required"].as_array().unwrap();
        for field in [
            "create_initial_workspace",
            "initial_workspace_id",
            "action_id",
            "path",
        ] {
            assert!(
                required.iter().any(|value| value == field),
                "missing {field}"
            );
        }
        assert!(schema.to_string().contains("repository_id"));
        assert!(exported.declarations.contains("export type Registration ="));
        assert!(!exported.declarations.contains("bigint"));
    }
}

#[cfg(test)]
mod parity_tests {
    use super::*;
    use crate::workspaces::Registration;
    use serde_json::json;

    #[test]
    fn pure_export_is_deterministic_and_uses_uuid_and_json_number_contracts() {
        let first = render();
        let second = render();
        assert_eq!(first.declarations, second.declarations);
        assert_eq!(first.schemas, second.schemas);
        assert_eq!(first.schemas["RepositoryId"]["format"], "uuid");
        assert!(first.schemas["RepositoryId"]["pattern"].is_string());
        assert!(first.declarations.contains("sequence: number"));
        assert!(first.declarations.contains("OwnedReply<T>"));
        assert_eq!(
            first.schemas["CoreSnapshot"]["$schema"],
            "https://json-schema.org/draft/2020-12/schema"
        );
    }

    #[test]
    fn input_defaults_do_not_omit_serialized_response_fields() {
        let registration: Registration = serde_json::from_value(json!({
            "action_id": "00000000-0000-0000-0000-000000000001", "path": "/projects/one", "state": "pending"
        })).unwrap();
        assert_eq!(
            serde_json::to_value(registration).unwrap(),
            json!({
                "action_id": "00000000-0000-0000-0000-000000000001", "path": "/projects/one", "state": "pending",
                "create_initial_workspace": false, "initial_workspace_id": null
            })
        );
    }

    #[test]
    fn nullable_omitted_and_default_fields_describe_serialization_separately() {
        // A pure supported-attribute case supplements the application corpus's actual DTOs.
        #[derive(Serialize, JsonSchema, TS)]
        struct Fields {
            #[serde(default)]
            count: u32,
            #[serde(default, skip_serializing_if = "Option::is_none")]
            omitted: Option<String>,
            nullable: Option<String>,
        }
        let serialized = serde_json::to_value(Fields {
            count: 0,
            omitted: None,
            nullable: None,
        })
        .unwrap();
        assert_eq!(serialized, json!({"count":0,"nullable":null}));
        let schema = SchemaSettings::draft2020_12()
            .for_serialize()
            .into_generator()
            .into_root_schema_for::<Fields>();
        let schema = serde_json::to_value(schema).unwrap();
        assert_eq!(schema["required"], json!(["count", "nullable"]));
        let declaration = Fields::decl(&Config::new().with_large_int("number"));
        assert!(declaration.contains("count: number"));
        assert!(declaration.contains("omitted?: string"));
        assert!(declaration.contains("nullable: string | null"));
    }
}
